import { PERMISSIONS, ROLE_CODES } from './rbac.constants.js';
import type { PermissionCode, RoleCode } from './rbac.constants.js';

export const WORKSPACES = {
  POS: 'POS',
  CALL_CENTER: 'CALL_CENTER',
  KITCHEN: 'KITCHEN',
  DISPATCH: 'DISPATCH',
  HR: 'HR',
  ACCOUNTING: 'ACCOUNTING',
  INVENTORY: 'INVENTORY',
  MANAGEMENT: 'MANAGEMENT',
} as const;

export type WorkspaceCode = (typeof WORKSPACES)[keyof typeof WORKSPACES];

const WORKSPACE_ROLES: Record<WorkspaceCode, readonly RoleCode[]> = {
  [WORKSPACES.POS]: [ROLE_CODES.CASHIER, ROLE_CODES.BRANCH_MANAGER, ROLE_CODES.CENTRAL_ADMIN, ROLE_CODES.OWNER],
  [WORKSPACES.CALL_CENTER]: [ROLE_CODES.CALL_CENTER_OPERATOR, ROLE_CODES.CALL_CENTER_SUPERVISOR, ROLE_CODES.CENTRAL_ADMIN, ROLE_CODES.OWNER],
  [WORKSPACES.KITCHEN]: [ROLE_CODES.KITCHEN, ROLE_CODES.BRANCH_MANAGER, ROLE_CODES.CENTRAL_ADMIN, ROLE_CODES.OWNER],
  [WORKSPACES.DISPATCH]: [ROLE_CODES.DISPATCHER, ROLE_CODES.CASHIER, ROLE_CODES.BRANCH_MANAGER, ROLE_CODES.CENTRAL_ADMIN, ROLE_CODES.OWNER],
  [WORKSPACES.HR]: [ROLE_CODES.HR_MANAGER, ROLE_CODES.CENTRAL_ADMIN, ROLE_CODES.OWNER],
  [WORKSPACES.ACCOUNTING]: [ROLE_CODES.ACCOUNTANT, ROLE_CODES.CENTRAL_ADMIN, ROLE_CODES.OWNER],
  [WORKSPACES.INVENTORY]: [ROLE_CODES.INVENTORY_MANAGER, ROLE_CODES.ACCOUNTANT, ROLE_CODES.BRANCH_MANAGER, ROLE_CODES.CENTRAL_ADMIN, ROLE_CODES.OWNER],
  [WORKSPACES.MANAGEMENT]: [ROLE_CODES.BRANCH_MANAGER, ROLE_CODES.CALL_CENTER_SUPERVISOR, ROLE_CODES.CENTRAL_ADMIN, ROLE_CODES.OWNER],
};

const WORKSPACE_REQUIRED_PERMISSIONS: Partial<Record<WorkspaceCode, readonly PermissionCode[]>> = {
  [WORKSPACES.POS]: [PERMISSIONS.ORDER_VIEW],
  [WORKSPACES.CALL_CENTER]: [PERMISSIONS.ORDER_VIEW],
  [WORKSPACES.KITCHEN]: [PERMISSIONS.KITCHEN_TICKET_MANAGE],
  [WORKSPACES.DISPATCH]: [PERMISSIONS.DRIVER_ASSIGN],
  [WORKSPACES.HR]: [PERMISSIONS.HR_EMPLOYEE_MANAGE],
  [WORKSPACES.ACCOUNTING]: [PERMISSIONS.REPORT_VIEW_FINANCIAL],
  [WORKSPACES.INVENTORY]: [PERMISSIONS.INVENTORY_VIEW],
  [WORKSPACES.MANAGEMENT]: [PERMISSIONS.REPORT_VIEW_OPERATIONAL],
};

export function workspacesForAccess(roles: readonly RoleCode[], permissions: readonly PermissionCode[]): readonly WorkspaceCode[] {
  return (Object.values(WORKSPACES) as WorkspaceCode[]).filter((workspace) => {
    const roleAllowed = WORKSPACE_ROLES[workspace].some((role) => roles.includes(role));
    if (!roleAllowed) return false;
    const required = WORKSPACE_REQUIRED_PERMISSIONS[workspace] ?? [];
    return required.every((permission) => permissions.includes(permission));
  });
}
